#!/usr/bin/env node

const crypto = require('crypto');
const fs = require('fs');
const os = require('os');
const path = require('path');

function readStdin() {
  return new Promise((resolve) => {
    let data = '';
    process.stdin.setEncoding('utf8');
    process.stdin.on('data', (chunk) => { data += chunk; });
    process.stdin.on('end', () => resolve(data));
  });
}

function argValue(args, name) {
  const index = args.indexOf(name);
  return index >= 0 && args[index + 1] ? args[index + 1] : '';
}

(async function main() {
  const args = process.argv.slice(2);
  const joinedArgs = args.join(' ');

  if (args.includes('--version') || args.includes('-v')) {
    process.stdout.write('mock-codebuddy 0.1.0\n');
    return;
  }

  if (args.includes('--help') || args.includes('-h')) {
    process.stdout.write('Usage: codebuddy [options] [prompt]\n');
    process.stdout.write('--model <model> Currently supported: (glm-5.1, glm-5.0, kimi-k2.5)\n');
    return;
  }

  if (args.includes('/model list') || /(^|\s)\/model\s+list(\s|$)/.test(joinedArgs)) {
    process.stdout.write([
      '可用模型列表如下：',
      '',
      '| 模型 | ID |',
      '|------|------|',
      '| GLM-5.1 ← 当前 | `glm-5.1` |',
      '| GLM-5.0 | `glm-5.0` |',
      '| Kimi-K2.5 | `kimi-k2.5` |',
      '',
      '使用 `/model <模型ID>` 切换模型。',
      '',
    ].join('\n'));
    return;
  }

  const sessionId = argValue(args, '--resume') || crypto.randomUUID();
  const modelName = argValue(args, '--model') || 'glm-5.1';
  const permissionMode = argValue(args, '--permission-mode') || 'default';
  const inputFormat = argValue(args, '--input-format');
  const usesStreamJson = inputFormat === 'stream-json';

  const rawInput = (await readStdin()).trim();
  let promptText = rawInput;
  let imageCount = 0;
  if (usesStreamJson) {
    let payload = null;
    try { payload = JSON.parse(rawInput.split('\n').find(Boolean) || '{}'); } catch {}
    const blocks = payload?.message?.content || [];
    imageCount = blocks.filter((block) => block?.type === 'image').length;
    promptText = blocks
      .filter((block) => block?.type === 'text')
      .map((block) => block.text || '')
      .join(' ')
      .trim();
  }

  const statePath = path.join(os.tmpdir(), `cc-web-mock-codebuddy-${sessionId}.json`);
  let state = {};
  try {
    state = JSON.parse(fs.readFileSync(statePath, 'utf8'));
  } catch {}

  if (promptText === '/compact') {
    state.compacted = true;
    fs.writeFileSync(statePath, JSON.stringify(state));
  }

  const isInitPrompt = promptText.includes('You are running cc-web\'s /init for a CodeBuddy session.');
  if (isInitPrompt) {
    fs.writeFileSync(path.join(process.cwd(), 'AGENTS.md'), '# AGENTS.md\n\nGenerated by mock CodeBuddy /init.\n');
  }

  if (promptText === 'trigger codebuddy context limit' && !state.compacted) {
    process.stderr.write('Context limit reached. Please use /compact and retry.\n');
    process.exit(1);
  }

  process.stdout.write(`${JSON.stringify({
    type: 'system',
    subtype: 'init',
    session_id: sessionId,
    model: modelName,
    permissionMode,
  })}\n`);

  if (promptText && promptText !== '/compact') {
    process.stdout.write(`${JSON.stringify({
      type: 'assistant',
      session_id: sessionId,
      message: {
        role: 'assistant',
        model: modelName,
        content: [
          {
            type: 'thinking',
            thinking: `Preparing mock CodeBuddy response for: ${promptText}`,
          },
        ],
      },
    })}\n`);
  }

  const responseText = promptText === '/compact'
    ? 'CodeBuddy compact finished.'
    : isInitPrompt
      ? 'CodeBuddy init finished.'
      : `CodeBuddy mock handled (${imageCount} image, ${permissionMode}): ${promptText || '[no text]'}`;

  process.stdout.write(`${JSON.stringify({
    type: 'assistant',
    session_id: sessionId,
    message: {
      role: 'assistant',
      model: modelName,
      content: [{ type: 'text', text: responseText }],
      usage: {
        input_tokens: 12,
        output_tokens: 6,
        cache_creation_input_tokens: 0,
        cache_read_input_tokens: 2,
      },
    },
  })}\n`);

  if (promptText === 'trigger codebuddy context limit' && state.compacted) {
    try { fs.unlinkSync(statePath); } catch {}
  }

  process.stdout.write(`${JSON.stringify({
    type: 'result',
    subtype: 'success',
    session_id: sessionId,
    total_cost_usd: 0,
    usage: {
      input_tokens: 12,
      output_tokens: 6,
      cache_creation_input_tokens: 0,
      cache_read_input_tokens: 2,
    },
    result: responseText,
  })}\n`);
})();
